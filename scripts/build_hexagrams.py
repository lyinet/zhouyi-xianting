out = []
for r in parsed:
    n = r['no']
    lt, ltr, wx, wb, wr, tr_, trr, ck, cn, cs = D[n]
    up, lo = R[r['upper']], R[r['lower']]
    palette_zh = [up['palette_zh'][0], lo['palette_zh'][0], ACCENT[lt]['zh']]
    palette_en = [up['palette_en'][0], lo['palette_en'][0], ACCENT[lt]['en']]
    if up['trigram'] == lo['trigram']:          # 八纯卦：单境双重，第二主色取本境次色
        palette_zh[1] = up['palette_zh'][1]
        palette_en[1] = up['palette_en'][1]
    out.append({
        'no': n, 'name': r['name'], 'symbol': r['symbol'],
        'upper': r['upper'], 'lower': r['lower'], 'lines': r['lines'],
        'upper_realm': up['realm'], 'upper_realm_en': up['realm_en'],
        'lower_realm': lo['realm'], 'lower_realm_en': lo['realm_en'],
        'guaci': r['guaci'], 'tuan': r['tuan'], 'daxiang': r['daxiang'],
        'dials': {
            'light': lt, 'light_reason': ltr,
            'weather': wx, 'weather_base': wb, 'weather_reason': wr,
            'terrain': tr_, 'terrain_reason': trr,
        },
        'creature': {'kind': ck, 'count': cn, 'state': cs},
        'palette_zh': palette_zh, 'palette_en': palette_en,
        'source': f"https://ctext.org/book-of-changes/{r['slug']}/zh",
    })

